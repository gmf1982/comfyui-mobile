export function getLang() {
  return state.settings.lang === 'en' ? 'en' : 'zh';
}

/** 切换语言（持久化由设置页的 saveSettings 负责）。 */
export function setLang(lang) {
  state.settings.lang = lang === 'en' ? 'en' : 'zh';
}

/** @param {keyof typeof T} key 兼容旧版 camelCase 键 */
export function t(text) {
  if (Object.prototype.hasOwnProperty.call(T, text)) return T[text];
  if (getLang() === 'en' && Object.prototype.hasOwnProperty.call(EN, text)) return EN[text];
  return text;
}

/** 带占位符的文案：tf('{n} 个文件', { n: 3 })；占位符 {name} 逐个替换。 */
export function tf(text, params) {
  let out = t(text);
  for (const [key, value] of Object.entries(params ?? {})) {
    out = out.split(`{${key}}`).join(String(value));
  }
  return out;
}
